document.addEventListener("click", e => {
  const act = e.target.closest("[data-act]");
  if (act){
    switch (act.dataset.act){
      case "close":   closeModal(); return;
      case "rules":   showRules(); return;
      case "newrun":      closeModal(); showModePicker(); return;
      case "newrun-free": closeModal(); newRun("free"); render(); return;
      case "newrun-run":  closeModal(); newRun("run"); render(); return;
      case "summary":     showRunSummary(); return;
      case "next":    nextRound(); return;
      case "mulligan": mulligan(); return;
      case "end":     endRound(); return;
      case "sort-cost":   sortMode = "cost"; render(); return;
      case "sort-points": sortMode = "points"; render(); return;
    }
  }
  const card = e.target.closest("[data-card]");
  if (card){
    const id = +card.dataset.card;
    // Shift-click marks a card for mulligan; a plain click plays it.
    if (e.shiftKey) toggleSelect(id); else playCard(id);
    return;
  }
  if (e.target === $("veil")) closeModal();
});

document.addEventListener("keydown", e => {
  if (e.key === "Escape") closeModal();
});

