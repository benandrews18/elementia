function showRoundOver(r){
  const flushRows = r.flushes.length
    ? r.flushes.map(f => `<tr><td>${ELEMENT_SUIT_LABEL[f.suit]} flush (${f.pips} pips)</td>
        <td class="num">+${f.mult}</td></tr>`).join("")
    : `<tr><td>No flushes</td><td class="num">+0</td></tr>`;

  const last = inRun() && state.round >= RUN_LENGTH;
  if (inRun() && !state.cleared){
    openModal(`Round ${state.round} — ${state.station}`,
      `<table>
         <tr><td>Points played (${state.played.length} cards)</td><td class="num">${r.base}</td></tr>
         ${flushRows}
         <tr><th>${r.base} × ${r.mult}</th><th class="num">${r.total.toLocaleString()}</th></tr>
       </table>
       <p style="margin-top:12px">Target was ${state.target.toLocaleString()} — missed, but a
         recorded run carries on so you can play all ${RUN_LENGTH} rounds.</p>`,
      last ? `<button type="button" class="btn primary" data-act="summary">Run summary ▸</button>`
           : `<button type="button" class="btn primary" data-act="next">Next round ▸</button>`);
    return;
  }
  if (state.cleared){
    const s = state.lastSP;
    openModal(`Round ${state.round} cleared`,
      `<table>
         <tr><td>Points played (${state.played.length} cards)</td><td class="num">${r.base}</td></tr>
         ${flushRows}
         <tr><th>${r.base} × ${r.mult}</th><th class="num">${r.total.toLocaleString()}</th></tr>
       </table>
       <p style="margin-top:12px">Target was ${state.target.toLocaleString()}.</p>
       <h4>Station Points earned</h4>
       <table>
         <tr><td>Clearing the round</td><td class="num">${s.base}</td></tr>
         <tr><td>Unused mulligans (${s.spare})</td><td class="num">${s.mulls}</td></tr>
         <tr><td>Beating the target over again</td><td class="num">${s.extra}</td></tr>
         <tr><th>Total</th><th class="num">${s.total}</th></tr>
       </table>
       <p style="margin-top:12px">You hold <b>${state.sp}</b> Station Points.
         Next round needs <b>${targetFor(state.round + 1).toLocaleString()}</b>.</p>`,
      last ? `<button type="button" class="btn primary" data-act="summary">Run summary ▸</button>`
           : `<button type="button" class="btn primary" data-act="next">Next round ▸</button>`);
  } else {
    openModal("Round lost",
      `<table>
         <tr><td>Points played (${state.played.length} cards)</td><td class="num">${r.base}</td></tr>
         ${flushRows}
         <tr><th>${r.base} × ${r.mult}</th><th class="num">${r.total.toLocaleString()}</th></tr>
       </table>
       <p style="margin-top:12px">You needed ${state.target.toLocaleString()}.
         You reached round ${state.round} and banked <b>${state.sp}</b> Station Points.</p>`,
      `<button type="button" class="btn primary" data-act="newrun">New run</button>`);
  }
}

