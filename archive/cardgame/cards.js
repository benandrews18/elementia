const SAVE_KEY = "elementia_solitaire_v3";
let state = null;
let sortMode = "cost";

function newRun(mode){
  rngState = (Math.random() * 4294967296) >>> 0;
  state = { v: 3, version: CONTENT_VERSION, round: 1, sp: 0, over: false,
            mode: mode === "run" && hasRun ? "run" : "free", history: [] };
  startRound();
}

const inRun = () => state.mode === "run";
const runRound = () => RECORDED_RUN[state.round - 1];

/* The deck in run mode is everything crafted up to this point in the run
   -- the cards you had actually built by then, nothing else. */
function runDeck(){
  const upto = DECK_THROUGH_CURRENT ? state.round : state.round - 1;
  const names = [];
  for (let i = 0; i < upto && i < RECORDED_RUN.length; i++){
    names.push(...RECORDED_RUN[i].crafted);
  }
  const byName = {};
  ITEM_CARDS.forEach(it => { byName[it.name] = it; });
  return names.filter(n => byName[n]).map(n => cardFrom(byName[n]));
}

function startRound(){
  state.target = targetFor(state.round);
  state.openingMulls = OPENING_MULLIGANS;
  state.mulls = ROUND_MULLIGANS;
  if (inRun()){
    const r = runRound();
    state.station = r.station;
    state.deck = shuffle(runDeck());
    state.store = storeFromElements(r[RUN_POOL_FIELD]);
  } else {
    state.station = null;
    state.deck = shuffle(buildItemDeck());
    state.store = buildStore();
  }
  state.hand = [];
  state.played = [];
  state.selected = [];
  state.roundOver = false;
  state.cleared = false;
  draw(MAX_HAND);
  if (inRun()){
    // Par has to be measured after the deal, since it depends on the hand.
    const par = parScore(state.hand, state.deck, state.store, mulligansLeft());
    state.par = par;
    state.target = Math.max(0, Math.round(par * PAR_FRACTION / 5) * 5);
  }
  save();
}

function draw(n){
  for (let i = 0; i < n && state.deck.length; i++) state.hand.push(state.deck.pop());
}

function save(){
  try { localStorage.setItem(SAVE_KEY, JSON.stringify({ ...state, rng: rngState, nextId })); }
  catch(e){}
}
function load(){
  try {
    const raw = localStorage.getItem(SAVE_KEY);
    if (!raw) return false;
    const s = JSON.parse(raw);
    if (!s || s.v !== 3 || s.version !== CONTENT_VERSION || !Array.isArray(s.hand)) return false;
    rngState = s.rng || 1; nextId = s.nextId || 0;
    delete s.rng; delete s.nextId;
    state = s;
    return true;
  } catch(e){ return false; }
}

///////////////////////////////////////////////////////////////////////
// Paying for a card
///////////////////////////////////////////////////////////////////////

const untapped = () => state.store.filter(e => !e.tapped);

/* Which store elements would pay for this card, or null if it cannot be
   paid for. Elements of the same suit are perfectly interchangeable for
   cost, so a greedy walk suit by suit is already optimal -- there is no
   choice here worth handing to the player, only the choice of which card
   to play at all. */
function payment(card, from){
  const need = tally(card.pips);
  const pool = from || untapped();
  const used = [];
  for (const suit in need){
    const have = pool.filter(e => e.suit === suit && !used.includes(e));
    if (have.length < need[suit]) return null;
    used.push(...have.slice(0, need[suit]));
  }
  return used;
}
const canPlay = card => payment(card) !== null;
const isFree = card => card.pips.length === 0;

/* ------------------------------------------------------------------
   PAR. A recorded round hands you a fixed deck and a fixed store, and
   those vary enormously across the run -- round 1 has no deck at all,
   round 20 has 69 cards but only 7 mana. The free-play ante curve is
   meaningless against that (it clears 0 of 20), so a run round sets its
   target by playing itself: a greedy pass over the same hand, store and
   deck gives par, and the target is a fraction of it.

   That makes every round a fair fight regardless of what the run brought,
   and the target is something you can actually beat by playing better
   than the greedy line -- which mostly means holding out for a flush
   instead of taking points as they come. */
const PAR_FRACTION = 0.7;

function parScore(hand, deck, store, mulls){
  const pool = store.map(e => ({ suit: e.suit, tapped: false }));
  let hd = hand.slice(), dk = deck.slice(), m = mulls;
  const played = [];
  const untapPool = () => pool.filter(e => !e.tapped);
  const pipsSoFar = () => {
    const t = {}; SUIT_ORDER.forEach(s => { t[s] = 0; });
    played.forEach(c => c.pips.forEach(s => { t[s]++; }));
    return t;
  };
  let guard = 0;
  while (guard++ < 200){
    const pips = pipsSoFar();
    const playable = hd.filter(c => payment(c, untapPool()));
    if (playable.length){
      playable.sort((a, b) => {
        const v = c => c.pips.length
          ? c.points / c.pips.length + 4 * Math.max(...c.pips.map(s => pips[s]))
          : c.points * 2;
        return v(b) - v(a);
      });
      const card = playable[0];
      (payment(card, untapPool()) || []).forEach(e => { e.tapped = true; });
      hd = hd.filter(c => c !== card);
      played.push(card);
      continue;
    }
    if (m > 0 && hd.length && dk.length){
      const dead = hd.filter(c => !payment(c, untapPool()));
      if (!dead.length) break;
      hd = hd.filter(c => !dead.includes(c));
      const drawn = dk.slice(-dead.length);
      dk = dk.slice(0, Math.max(0, dk.length - dead.length));
      hd = hd.concat(drawn);
      m--;
      continue;
    }
    break;
  }
  const base = played.reduce((n, c) => n + c.points, 0);
  const t = {}; SUIT_ORDER.forEach(s => { t[s] = 0; });
  played.forEach(c => c.pips.forEach(s => { t[s]++; }));
  const mult = 1 + SUIT_ORDER.reduce((n, s) => n + flushMultFor(t[s]), 0);
  return base * mult;
}

function playCard(id){
  if (state.roundOver) return;
  const card = state.hand.find(c => c.id === id);
  if (!card) return;
  const pay = payment(card);
  if (!pay){
    const need = tally(card.pips);
    const short = Object.keys(need)
      .filter(s => untapped().filter(e => e.suit === s).length < need[s])
      .map(s => ELEMENT_SUIT_LABEL[s]);
    toast(`Not enough untapped ${short.join(" and ")}.`, "bad");
    return;
  }
  pay.forEach(e => { e.tapped = true; });
  state.hand = state.hand.filter(c => c.id !== id);
  state.played.push(card);
  /* No refill. The hand you drew is the round's whole resource, the way a
     Gwent round is -- that is what makes "the round ends when you can make
     no more moves" a real ending. Refilling after every play made it
     nearly unreachable, since the 25 free cards are always playable: a bot
     would just keep drawing and playing 26 of the 79 cards every round. */
  flash(card);
  render();
  save();
  if (!hasAnyMove()) setTimeout(() => { if (!state.roundOver) endRound(); }, 500);
}

/* A round is over once nothing in hand can be paid for and there is no
   mulligan left to change that. */
function hasAnyMove(){
  if (state.hand.some(canPlay)) return true;
  return mulligansLeft() > 0 && state.hand.length > 0;
}

/* The opening mulligan only exists until the first card is played, and is
   simply lost if unused -- so it reads as "fix the hand you were dealt",
   not as a third free swap you can bank. */
const openingOpen = () => state.played.length === 0 && state.openingMulls > 0;
const mulligansLeft = () => (openingOpen() ? state.openingMulls : 0) + state.mulls;

function mulligan(){
  if (state.roundOver) return;
  const picked = state.hand.filter(c => state.selected.includes(c.id));
  if (!picked.length){ toast("Select the cards you want to swap.", "bad"); return; }
  if (mulligansLeft() <= 0){ toast("No mulligans left this round.", "bad"); return; }
  const usedOpening = openingOpen();
  if (usedOpening) state.openingMulls--; else state.mulls--;
  state.hand = state.hand.filter(c => !state.selected.includes(c.id));
  // Swapped cards go to the bottom, so a big deck still cycles honestly.
  state.deck.unshift(...picked);
  state.selected = [];
  draw(picked.length);   // one-for-one swap; the hand never grows
  const left = mulligansLeft();
  toast(`${usedOpening ? "Opening mulligan" : "Mulligan"}: swapped ${picked.length} card${picked.length === 1 ? "" : "s"} — ${left} left`);
  render();
  save();
  if (!hasAnyMove()) setTimeout(() => { if (!state.roundOver) endRound(); }, 500);
}

function toggleSelect(id){
  if (state.roundOver) return;
  const i = state.selected.indexOf(id);
  if (i === -1) state.selected.push(id); else state.selected.splice(i, 1);
  render();
}

///////////////////////////////////////////////////////////////////////
// Scoring
///////////////////////////////////////////////////////////////////////

/* Every pip actually paid across everything played this round, by suit.
   Free cards contribute points but no pips, so they never help a flush --
   which is the trade for costing nothing. */
function pipsPlayed(){
  const t = {};
  SUIT_ORDER.forEach(s => { t[s] = 0; });
  state.played.forEach(c => c.pips.forEach(s => { t[s]++; }));
  return t;
}

function roundScore(){
  const base = state.played.reduce((n, c) => n + c.points, 0);
  const pips = pipsPlayed();
  const flushes = SUIT_ORDER
    .map(s => ({ suit: s, pips: pips[s], mult: flushMultFor(pips[s]) }))
    .filter(f => f.mult > 0);
  const mult = 1 + flushes.reduce((n, f) => n + f.mult, 0);
  return { base, pips, flushes, mult, total: base * mult };
}

function endRound(){
  if (state.roundOver) return;
  state.roundOver = true;
  const r = roundScore();
  state.score = r.total;
  state.cleared = r.total >= state.target;
  if (state.cleared && state.target > 0){
    const extra = Math.floor(r.total / state.target) - 1;
    const spare = mulligansLeft();
    const sp = SP_CLEAR + spare * SP_PER_UNUSED_MULL + extra * SP_PER_EXTRA_TARGET;
    state.sp += sp;
    state.lastSP = { base: SP_CLEAR, mulls: spare * SP_PER_UNUSED_MULL,
                     extra: extra * SP_PER_EXTRA_TARGET, total: sp, spare };
  } else {
    state.lastSP = { base: 0, mulls: 0, extra: 0, total: 0, spare: mulligansLeft() };
    // A recorded run is a test harness, not a gauntlet: missing a target
    // records the round and moves on rather than ending the run, so all
    // 20 rounds can actually be played through.
    if (!inRun()) state.over = true;
  }
  state.history.push({
    round: state.round, station: state.station,
    base: r.base, mult: r.mult, total: r.total, target: state.target,
    played: state.played.length, deck: state.deck.length + state.hand.length + state.played.length,
    manaLeft: untapped().length, store: state.store.length,
    cleared: state.cleared, sp: state.lastSP.total,
  });
  if (inRun() && state.round >= RUN_LENGTH) state.over = true;
  render();
  save();
  setTimeout(() => showRoundOver(r), 380);
}

function nextRound(){
  if (inRun() && state.round >= RUN_LENGTH){ showRunSummary(); return; }
  state.round++;
  startRound();
  closeModal();
  render();
}

