/* =====================================================================
   Elementia -- Solitaire.  A Gwent-shaped solo card game.

   Content comes from data.js (regenerated by build_cards.py out of
   build_guide.py, the curated suit CSV and elementia.html's
   ITEM_SUIT_COST_TABLE) and from ../boardgame/icons.js for the art.
   Nothing here hardcodes an item, a point value or a suit.

   THE SHAPE OF A ROUND
   Your element store is your mana, and all of it is in play and untapped
   from the moment the round begins -- no drawing lands, no ramp. Item
   cards cost the suit pips printed on them; you tap matching elements to
   pay. Twenty-five of the seventy-nine items cost nothing at all and are
   always free to play. The round ends when you cannot, or choose not to,
   play anything more. Everything you played is then totalled and
   multiplied by whatever flushes you managed to stack.

   WHAT IS SPECIFIED vs WHAT IS INVENTED
   Specified: the element store as always-in-play mana, tapping by suit to
   pay a card's printed cost, no-pip cards being free, pips counting as
   set size, a mulligan limit of 3, scoring at end of round, a suit-flush
   multiplier, and Station Points as the payout.
   Invented here, every one of them a constant below: the size and make-up
   of the store, hand size, the exact flush thresholds and multipliers, the
   target curve, and the Station Point formula.
   ===================================================================== */

///////////////////////////////////////////////////////////////////////
// Tunables
///////////////////////////////////////////////////////////////////////

/* The hand is capped: ten cards is the most you may ever hold, and it
   does not grow across a run. That makes the hand a hard ceiling on how
   much you can score in a round, so the target curve below is tuned
   against what ten cards can actually do rather than against an
   ever-growing one. */
const MAX_HAND = 10;

/* Mulligans come in two kinds. One is an opening mulligan, usable only on
   the hand you were dealt -- play a single card and it is gone, the way an
   opening mulligan works anywhere else. The other two are yours to spend
   whenever during the round. Either kind swaps any number of cards, one
   for one. */
const OPENING_MULLIGANS = 1;
const ROUND_MULLIGANS = 2;

/* The store is the mana you brought. It grows a little each round, which
   is the only progression in a run -- but note it cannot grow the score
   without bound, because the ten-card hand caps how much you can spend it
   on. Measured leftovers climb past a store of roughly 16. */
const STORE_BASE = 12;
const STORE_GROWTH = 1;
const storeSizeFor = round => STORE_BASE + (round - 1) * STORE_GROWTH;

/* Flush: at the end of the round, count every suit pip you actually paid
   for across all the cards you played, suit by suit. Each suit that
   reaches a threshold adds to a single shared multiplier, so going deep
   in one suit and spreading across several are both viable -- one big
   flush and three small ones are worth the same +3.
   Read as: this many pips of one suit is worth this much mult. */
const FLUSH_TIERS = [
  { pips: 3,  mult: 1 },
  { pips: 5,  mult: 2 },
  { pips: 7,  mult: 3 },
  { pips: 10, mult: 5 },
];
const flushMultFor = pips => {
  let m = 0;
  FLUSH_TIERS.forEach(t => { if (pips >= t.pips) m = t.mult; });
  return m;
};

/* Target curve. Round 1 should fall to a competent first hand; each round
   after multiplies, and the store does not grow, so later rounds lean on
   flushes rather than on raw volume. */
const TARGET_BASE = 110;
const TARGET_GROWTH = 1.15;
const targetFor = round => Math.round(TARGET_BASE * Math.pow(TARGET_GROWTH, round - 1) / 5) * 5;

/* Station Points -- the payout the board game will eventually spend at a
   station in place of rolling dice. */
const SP_CLEAR = 3;
const SP_PER_UNUSED_MULL = 1;
const SP_PER_EXTRA_TARGET = 1;

const SUIT_ORDER = ["organic", "reactive", "earth", "metal"];

/* ------------------------------------------------------------------
   RUN MODE -- play the recorded 20-round run in run.js instead of a
   random deck against a random store. Each round hands you the element
   pool that run actually held and a deck of exactly the cards crafted by
   then, so a round can be played and replayed against real inputs.

   RUN_POOL_FIELD picks which reconstructed pool becomes the mana store:
     "pool"    -- what was held once that round's dice were in (default)
     "carried" -- what was held as the round opened, before rolling
   DECK_THROUGH_CURRENT includes the current round's own crafts in the
   deck; turn it off to draw only from what existed before the round.
   ------------------------------------------------------------------ */
const RUN_POOL_FIELD = "pool";
const DECK_THROUGH_CURRENT = true;
const hasRun = typeof RECORDED_RUN !== "undefined" && RECORDED_RUN.length;
const RUN_LENGTH = hasRun ? RECORDED_RUN.length : 0;

///////////////////////////////////////////////////////////////////////
// Helpers
///////////////////////////////////////////////////////////////////////

const $ = id => document.getElementById(id);
const esc = s => String(s).replace(/[&<>"']/g, c =>
  ({ "&":"&amp;", "<":"&lt;", ">":"&gt;", '"':"&quot;", "'":"&#39;" }[c]));
/* Same contract as the board game: the emoji field is a lookup key into
   the shared icon bundle, never a glyph to render. */
const em = key => (typeof ICONS !== "undefined" && ICONS[key]) || esc(key);
const suitArt = s => `<img class="suit-art" src="${SUIT_ART[s]}" alt="${s}">`;

let rngState = 1;
function rnd(){
  rngState |= 0; rngState = (rngState + 0x6D2B79F5) | 0;
  let t = Math.imul(rngState ^ (rngState >>> 15), 1 | rngState);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
}
function shuffle(a){
  a = a.slice();
  for (let i = a.length - 1; i > 0; i--){
    const j = Math.floor(rnd() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}
const tally = list => list.reduce((m, s) => (m[s] = (m[s] || 0) + 1, m), {});

///////////////////////////////////////////////////////////////////////
// Deck and store
///////////////////////////////////////////////////////////////////////

let nextId = 0;

const cardFrom = it => ({
  id: nextId++, kind: "item",
  name: it.name, emoji: it.emoji, tier: it.tier, points: it.points,
  station: it.station, stationColor: it.stationColor, stationEmoji: it.stationEmoji,
  suit: it.suit,               // the curated single suit -- flavour only
  pips: it.pips.slice(),       // the real cost, and what flushes count
  components: it.components,   // the recipe, drawn as icons on the face
});

const buildItemDeck = () => ITEM_CARDS.map(cardFrom);

/* THE LOOP: the store is the element pool the player brings in from the
   board game -- the elements you rolled at stations become the mana you
   spend here, and the Station Points you win go back the other way to be
   spent at a station in place of rolling. So the store is built from a
   plain {symbol: count} map, which is exactly the shape the board game
   already keeps its held elements in (player.elements). Wiring the two
   together is a matter of handing that object across; standalone play
   seeds one at random.

   The random seed is deliberately unbalanced across suits -- being short
   on reactive is a real position to play out of, not a rounding error. */
function storeFromElements(counts){
  const out = [];
  Object.keys(counts).forEach(sym => {
    for (let i = 0; i < counts[sym]; i++){
      out.push({ id: nextId++, kind: "element", sym,
                 name: ELEMENT_NAMES[sym] || sym,
                 suit: ELEMENT_SUIT[sym], tapped: false });
    }
  });
  return out.sort((a, b) => SUIT_ORDER.indexOf(a.suit) - SUIT_ORDER.indexOf(b.suit)
    || (ATOMIC_NUMBER[a.sym] || 0) - (ATOMIC_NUMBER[b.sym] || 0));
}

function randomElementCounts(n){
  const counts = {};
  for (let i = 0; i < n; i++){
    const sym = CORE_ELEMENT_SYMS[Math.floor(rnd() * CORE_ELEMENT_SYMS.length)];
    counts[sym] = (counts[sym] || 0) + 1;
  }
  return counts;
}

const buildStore = () =>
  storeFromElements(randomElementCounts(storeSizeFor(state ? state.round : 1)));

