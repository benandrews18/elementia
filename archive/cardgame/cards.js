/* The card face follows images/Card Design Reference.png:

     - suit cost as a COLUMN down the left edge, one badge per pip. That
       placement is load-bearing: the hand is fanned, so the left strip of
       a card is the only part of it you can see, and cost is the thing
       you must be able to read to know what is playable.
     - points in a star, top right
     - art, then the name beneath it
     - a rule, then "Components:" as ICONS -- items by their art, elements
       as their own letter box. No ingredient names; there is no room for
       them at phone size and the icons carry it.
     - the station badge in the bottom-right corner.
*/
function costHTML(card){
  if (isFree(card)) return `<span class="c-cost free"><span class="freepip">F</span></span>`;
  const pool = untapped();
  const need = tally(card.pips);
  const short = {};
  Object.keys(need).forEach(s => {
    short[s] = Math.max(0, need[s] - pool.filter(e => e.suit === s).length);
  });
  const seen = {};
  return `<span class="c-cost">` + card.pips.map(s => {
    seen[s] = (seen[s] || 0) + 1;
    const ok = seen[s] <= need[s] - short[s];
    return `<span class="cpip ${ok ? "ok" : "short"}" style="--suit:${SUIT_COLOR[s]}"
      title="${ELEMENT_SUIT_LABEL[s]}">${suitArt(s)}</span>`;
  }).join("") + `</span>`;
}

function componentsHTML(card){
  const parts = (card.components || []).map(c => c.kind === "element"
    ? `<span class="cmp el" title="${esc(c.name)}">${esc(c.name)}</span>`
    : `<span class="cmp" title="${esc(c.name)}">${em(c.emoji)}</span>`);
  return parts.join(`<span class="cmp-plus">+</span>`);
}

/* Fan geometry.

   One row of ten on a 414px screen leaves only ~26px of each card
   showing. That is enough for the cost column down the left edge, but
   not enough to tell WHICH card it is, so nine of the ten read as blank
   slabs. Splitting into two shallower rows roughly doubles the visible
   slice, and costs vertical space the hand zone had spare anyway.

   Cards rotate about their own base. Rotating about a point far below
   the card -- the obvious way to draw a fan -- swings the end cards
   ~50px sideways and straight off the screen. */
const HAND_CARD_W = 126;
const HAND_INSET = 12;
const ROW_GAP = 116;
const FAN_BOTTOM = 24;
const ROW_SPLIT = 5;      // more than this many cards and the fan doubles up

function fanPos(i, n){
  const hw = ($("hand") && $("hand").clientWidth) || 414;
  const rows = n > ROW_SPLIT ? 2 : 1;
  const per = Math.ceil(n / rows);
  const row = Math.floor(i / per);
  const inRow = i % per;
  const count = Math.min(per, n - row * per);

  const avail = hw - HAND_INSET * 2;
  const step = count > 1
    ? Math.min(HAND_CARD_W * 0.62, (avail - HAND_CARD_W) / (count - 1))
    : 0;
  const rowW = (count - 1) * step + HAND_CARD_W;
  const x = HAND_INSET + (avail - rowW) / 2 + inRow * step;

  const mid = (count - 1) / 2;
  const off = inRow - mid;
  return {
    x: Math.round(x),
    y: FAN_BOTTOM + (rows - 1 - row) * ROW_GAP,
    tilt: +(off * 2.4).toFixed(2),
    dip: +(Math.pow(Math.abs(off), 1.6) * 1.4).toFixed(1),
    // later rows sit in front; within a row, later cards overlap earlier
    z: row * 100 + inRow + 1,
  };
}

function cardHTML(c, pos){
  const sel = state.selected.includes(c.id);
  const playable = !state.roundOver && canPlay(c);
  const cls = ["card", sel ? "sel" : "", playable ? "playable" : "unplayable",
               isFree(c) ? "freecard" : ""].join(" ");
  return `<button type="button" class="${cls}" data-card="${c.id}"
      style="left:${pos.x}px; bottom:${pos.y}px; --tilt:${pos.tilt}deg;
             --dip:${pos.dip}px; z-index:${pos.z}"
      title="${esc(c.name)} — ${c.points} pt${c.points === 1 ? "" : "s"}${isFree(c) ? ", free" : ""}">
    ${costHTML(c)}
    <span class="c-pts"><i>${c.points}</i></span>
    <span class="c-art">${em(c.emoji)}</span>
    <span class="c-name">${esc(c.name)}</span>
    <span class="c-foot">
      <span class="c-comp-label">Components</span>
      <span class="c-comps">${componentsHTML(c)}</span>
    </span>
    <span class="c-station" title="${esc(c.station)}">${em(c.stationEmoji)}</span>
  </button>`;
}

/* One stack per suit, per images/Card Game UI Reference.png. Cards
   overlap so that only a top strip of each shows, and the pool reads by
   depth rather than by a count badge -- the number printed on an element
   card is its ATOMIC number, not a quantity.

   Untapped sit at the bottom of the stack, fully visible; spent ones ride
   above them, dimmed. The overlap step shrinks as a stack deepens so the
   worst case in the recorded run (13 reactive, round 9) still fits. */
/* Read from CSS so the stack can never outgrow its zone -- the store
   height shrinks on short screens (see the height media queries). */
const stackMetrics = () => {
  const cs = getComputedStyle(document.documentElement);
  const zone = parseInt(cs.getPropertyValue("--store-h")) || 272;
  const card = parseInt(cs.getPropertyValue("--ecard-h")) || 102;
  // zone padding (8) + the suit header (24) + 2px of breathing room
  return { STACK_H: zone - 34, ECARD_H: card, STEP_MAX: 20 };
};

function storeHTML(){
  return SUIT_ORDER.map(suit => {
    const all = state.store.filter(e => e.suit === suit);
    const live = all.filter(e => !e.tapped).length;
    // spent first so they sit behind, untapped last so one reads in full
    const ordered = [...all.filter(e => e.tapped), ...all.filter(e => !e.tapped)];
    const { STACK_H, ECARD_H, STEP_MAX } = stackMetrics();
    const step = ordered.length > 1
      ? Math.min(STEP_MAX, (STACK_H - ECARD_H) / (ordered.length - 1))
      : 0;
    const cards = ordered.map((e, i) => `
      <span class="ecard ${e.tapped ? "tapped" : ""} ${i === ordered.length - 1 ? "top" : ""}"
            style="top:${Math.round(i * step)}px; z-index:${i + 1}"
            title="${esc(e.name)} — ${ELEMENT_SUIT_LABEL[suit]}${e.tapped ? " (spent)" : ""}">
        <span class="ecard-strip">
          <span class="ecard-no">${ATOMIC_NUMBER[e.sym] || ""}</span>
          <span class="ecard-suit">${suitArt(suit)}</span>
        </span>
        <span class="ecard-body">
          <span class="ecard-sym">${esc(e.sym)}</span>
          <span class="ecard-name">${esc(e.name)}</span>
        </span>
      </span>`).join("");
    return `<div class="stack ${live ? "" : "spent"}" style="--suit:${SUIT_COLOR[suit]}">
      <div class="stack-head">${suitArt(suit)}<b>${live}</b><s>/${all.length}</s></div>
      <div class="stack-cards" style="height:${Math.round(
        Math.max(ECARD_H, (Math.max(1, ordered.length) - 1) * step + ECARD_H))}px">
        ${cards || `<span class="ecard empty"></span>`}
      </div>
    </div>`;
  }).join("");
}

function render(){
  const r = roundScore();

  $("roundNo").textContent = inRun() ? `${state.round} / ${RUN_LENGTH}` : state.round;
  $("stationTag").textContent = state.station || "";
  $("stationTag").hidden = !state.station;
  $("target").textContent = state.target.toLocaleString();
  $("parTag").textContent = inRun() && state.par ? `par ${state.par.toLocaleString()}` : "";
  $("parTag").hidden = !(inRun() && state.par);
  $("score").textContent = r.total.toLocaleString();
  $("goalFill").style.width =
    (state.target > 0 ? Math.min(100, 100 * r.total / state.target) : 100) + "%";
  $("goalFill").classList.toggle("done", r.total >= state.target);
  $("mullsLeft").textContent = mulligansLeft();
  $("mullsLeft").classList.toggle("opening", openingOpen());
  $("deckLeft").textContent = state.deck.length;
  const free = untapped().length;
  $("manaLeft").textContent = `${free}/${state.store.length}`;
  $("spChip").innerHTML = `<b>${state.sp}</b><span>Station Points</span>`;

  $("store").innerHTML = storeHTML();

  /* Gwent-style readout: the running number is the row total -- the plain
     sum of what you have played. Flushes are not folded in until the round
     is scored, so they show as a track of what each suit has banked and
     what it is worth, with the projection kept deliberately small. */
  $("chips").textContent = r.base;
  $("readoutProjection").innerHTML = r.mult > 1
    ? `flushes at end of round: <b>×${r.mult}</b> → <b>${r.total.toLocaleString()}</b>`
    : `no flushes yet — ${FLUSH_TIERS[0].pips} pips of one suit is +${FLUSH_TIERS[0].mult}`;
  $("readoutName").innerHTML = SUIT_ORDER.map(s => {
    const n = r.pips[s];
    const m = flushMultFor(n);
    const next = FLUSH_TIERS.find(tt => n < tt.pips);
    return `<span class="flush-tag ${m ? "lit" : ""}" style="--suit:${SUIT_COLOR[s]}"
        title="${esc(ELEMENT_SUIT_LABEL[s])}: ${n} pip${n === 1 ? "" : "s"} played${
          next ? `, ${next.pips - n} more for +${next.mult}` : ""}">
      ${suitArt(s)}<b>${n}</b>${m ? `<i>+${m}</i>` : ""}</span>`;
  }).join("");

  const cards = [...state.hand];
  cards.sort((a, b) => sortMode === "cost"
    ? (a.pips.length - b.pips.length) || (b.points - a.points)
    : (b.points - a.points) || (a.pips.length - b.pips.length));
  const n = cards.length;
  $("hand").innerHTML = n
    ? cards.map((c, i) => cardHTML(c, fanPos(i, n))).join("")
    : `<p class="hand-empty">Hand empty — end the round to score it.</p>`;

  $("played").innerHTML = state.played.length
    ? state.played.map(c => `<span class="chip-card" style="--suit:${c.pips.length ? SUIT_COLOR[c.pips[0]] : "#8e97a8"}"
        title="${esc(c.name)} — ${c.points} pts">${em(c.emoji)}<b>${c.points}</b></span>`).join("")
    : `<span class="played-empty">Nothing played yet.</span>`;

  $("sortCost").classList.toggle("on", sortMode === "cost");
  $("sortPoints").classList.toggle("on", sortMode === "points");
  $("mullBtn").disabled = state.roundOver || !state.selected.length || mulligansLeft() <= 0;
  $("mullBtn").textContent = openingOpen() ? "Opening mull" : "Mulligan";
  $("endBtn").disabled = state.roundOver;
}

