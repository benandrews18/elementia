let pendingSeats = 1;
function showNewGame(){
  pendingSeats = state ? state.players.length : 1;
  const seats = [1,2,3,4].map(n =>
    `<button type="button" data-seats="${n}" class="${n === pendingSeats ? "on" : ""}">${n === 1 ? "Solo" : n + " players"}</button>`).join("");
  openModal("New game",
    `<p>Start a fresh board. Your current game will be discarded.</p>
     <h4>Players</h4>
     <div class="seat-count">${seats}</div>
     <p style="margin-top:12px;font-size:12px">Everyone shares one board, one set of tier decks and
       one Item Display; each player keeps their own elements, built items and Bingo card. Deck copy
       counts scale with the player count, and Capstones are unique — first to build one keeps it.</p>`,
    `<button type="button" class="btn" data-act="close">Cancel</button>
     <button type="button" class="btn primary" data-act="start">Start</button>`);
}

function toast(msg, kind){
  const el = document.createElement("div");
  el.className = "toast " + (kind || "");
  el.textContent = msg;
  $("toasts").appendChild(el);
  setTimeout(() => el.remove(), 2600);
}

function showStation(name){
  const s = STATION_BY_NAME[name];
  const p = me();
  const sells = ALL_ITEMS.filter(n => ITEM[n].station === name);
  openModal(name,
    `<p>Dice pool: ${sortedDice(s).map(sym =>
        `<span class="ping elem">${esc(sym)}</span>`).join(" ")}</p>
     <p>${p.visited[name] ? "✓ Visited." : "Not visited yet."}
        Connects to: ${[...(MAP_ADJ[name] || [])].map(esc).join(", ")}.</p>
     <h4>Home station for (${sells.length})</h4>
     <p class="cingredients">${sells.map(n =>
        `<span class="ping ${owns(p,n) ? "have" : ""}"><span class="ping-icon">${em(ITEM[n].emoji)}</span>${esc(n)}</span>`).join("")}</p>`);
}

