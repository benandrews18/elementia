function needsOf(reqs){
  const els = {}, items = [];
  reqs.forEach(r => {
    if (r.kind === "element") els[r.name] = (els[r.name] || 0) + 1;
    else if (!items.some(i => i.name === r.name)) items.push(r);
  });
  return { els, items };
}
const heldTotal = p => Object.values(p.elements).reduce((a, b) => a + b, 0);
const feeOf = name => CRAFT_COST[tierOf(name)] || 0;

/* How many element tokens a recipe actually consumes by name -- catalysts
   (`*`) are named but never spent, so they do not count toward what the
   craft fee has left to draw on. */
function namedSpend(name){
  const { els } = needsOf(ITEM[name].reqs);
  let n = 0;
  for (const sym in els){
    const isCat = ITEM[name].reqs.some(r => r.name === sym && r.kind === "element" && r.catalyst);
    if (!isCat) n += els[sym];
  }
  return n;
}

/* Crafting is open: any card in the display can be built from anywhere,
   so long as the player holds its named elements, already owns its item
   ingredients, and can still cover the craft fee out of what is left. A
   card's station badge is provenance, not a gate. */
function canPay(p, name){
  if (owns(p, name)) return false;
  const { els, items } = needsOf(ITEM[name].reqs);
  for (const sym in els) if (count(p, sym) < els[sym]) return false;
  for (const it of items) if (!owns(p, it.name)) return false;
  return heldTotal(p) - namedSpend(name) >= feeOf(name);
}

/* The fee comes off the player's deepest stacks first, which is both the
   obvious play and the one that keeps scarce singletons available for
   recipes that name them specifically. */
function payFee(p, k){
  const paid = [];
  for (let i = 0; i < k; i++){
    const sym = Object.keys(p.elements).sort((a, b) => p.elements[b] - p.elements[a])[0];
    if (!sym) break;
    p.elements[sym]--;
    paid.push(sym);
    if (p.elements[sym] <= 0) delete p.elements[sym];
  }
  return paid;
}
const canBuild = (p, name) => canPay(p, name);

function missingFor(p, name){
  const { els, items } = needsOf(ITEM[name].reqs);
  const out = [];
  for (const sym in els){
    const short = els[sym] - count(p, sym);
    if (short > 0) out.push(short > 1 ? short + "x " + sym : sym);
  }
  items.forEach(it => { if (!owns(p, it.name)) out.push(it.name); });
  const feeShort = feeOf(name) - (heldTotal(p) - namedSpend(name));
  if (!out.length && feeShort > 0) out.push(`${feeShort} more element${feeShort === 1 ? "" : "s"} for the craft cost`);
  return out;
}

/* Travel is constrained to MAP_EDGES, with the two unlocks the digital
   game already defines: the Ocean<->Observatory shortcut opens once the
   player has actually stood at the Observatory, and owning a Helicopter
   makes every station reachable. at === null means "choosing where to
   start", so on turn one every station qualifies. */
function edgeUnlocked(p, a, b){
  if ((a === SHORTCUT[0] && b === SHORTCUT[1]) || (a === SHORTCUT[1] && b === SHORTCUT[0]))
    return !!p.visited[SHORTCUT[1]];
  return true;
}
function canTravel(p, to){
  if (p.at === null) return true;
  if (p.at === to) return false;              // staying put is not a move
  if (owns(p, "Helicopter")) return true;
  return !!(MAP_ADJ[p.at] && MAP_ADJ[p.at].has(to) && edgeUnlocked(p, p.at, to));
}

function travel(to){
  const p = me();
  if (state.phase !== "travel" || !canTravel(p, to)) return;
  const first = p.at === null;
  p.at = to;
  p.visited[to] = true;
  state.phase = "gather";
  log(`${p.name} ${first ? "starts at" : "travels to"} ${to}`);
  render();
  save();
}

function roll(){
  const p = me();
  if (state.phase !== "gather" || !p.at) return;
  const dice = sortedDice(STATION_BY_NAME[p.at]);
  const faces = Array.from({ length: DATA.take }, () => rndInt(6) + 1);
  showRoll(p.at, dice, faces, () => {
    faces.forEach(f => {
      const sym = dice[f - 1];
      p.elements[sym] = (p.elements[sym] || 0) + 1;
    });
    state.phase = "build";
    log(`${p.name} rolls ${faces.map(f => dice[f-1]).join(" ")}`);
    render();
    faces.forEach(f => bumpElement(dice[f - 1]));
    save();
  });
}

function build(name){
  const p = me();
  if (state.phase !== "build"){ toast("Roll for elements first.", "bad"); return; }
  if (owns(p, name)) return;
  if (!canPay(p, name)){
    toast("Still need: " + missingFor(p, name).join(", "), "bad");
    return;
  }
  const { els } = needsOf(ITEM[name].reqs);
  // Only raw elements are ever spent; built items are permanent, and an
  // explicit `*` catalyst is exempt even among elements.
  for (const sym in els){
    const isCat = ITEM[name].reqs.some(r => r.name === sym && r.kind === "element" && r.catalyst);
    if (!isCat) p.elements[sym] = count(p, sym) - els[sym];
  }
  Object.keys(p.elements).forEach(k => { if (p.elements[k] <= 0) delete p.elements[k]; });
  const fee = payFee(p, feeOf(name));

  p.items.push(name);

  if (ITEM[name].tier === "CAPSTONE"){
    // Exactly one of each capstone exists, so this claims it for good.
    state.capstoneOwner[name] = state.active;
  } else {
    // Pull this copy off the face-up row and slide a fresh card into the
    // same slot from the deck.
    const t = tierOf(name);
    const i = state.river[t].indexOf(name);
    if (i !== -1){
      state.river[t].splice(i, 1);
      if (state.decks[t].length) state.river[t].splice(i, 0, state.decks[t].shift());
    }
  }

  const won = checkBingo(p);
  log(`${p.name} builds ${name} (+${ITEM[name].points})`);
  toast(`Built ${name}  +${ITEM[name].points} pts` + (fee.length ? `  ·  cost ${fee.join(" ")}` : ""), "good");
  won.forEach(() => toast(`BINGO! +${BINGO_LINE_BONUS} pts`, "good"));

  if (CAPSTONES.every(c => c in state.capstoneOwner)) return endGame();
  render();
  save();
}

/* 3 of any one element -> 1 of any other, any number of times on your own
   turn. This is what keeps a run of bad dice recoverable: every station
   pours out the same six elements, so without a conversion valve a player
   who needs one Ti has no way to ever get it except by standing somewhere
   that rolls it. */
const canConvert = (p, from) => count(p, from) >= CONVERT_COST;
function convert(from, to){
  const p = me();
  if (state.over || from === to) return;
  if (!canConvert(p, from)){ toast(`Need ${CONVERT_COST} ${from} to convert.`, "bad"); return; }
  p.elements[from] = count(p, from) - CONVERT_COST;
  if (p.elements[from] <= 0) delete p.elements[from];
  p.elements[to] = count(p, to) + 1;
  log(`${p.name} converts ${CONVERT_COST} ${from} -> 1 ${to}`);
  toast(`${CONVERT_COST} ${from} → 1 ${to}`, "good");
  closeModal();
  render();
  bumpElement(to);
  save();
}

/* Restock: bottom-deck a tier's whole face-up row in place and deal a
   fresh one. Once per tier per turn.

   NOT one of the rules as written -- added because crafting is gated to
   the station on the card, so roughly one face-up card in eight is
   actually buyable where you are standing. Without a way to churn the
   row, a turn where the display happens to hold nothing from your station
   is a turn you simply cannot build, through no decision of your own.
   Delete restock() and its deck button if you would rather live with
   that; nothing else depends on it. */
function restock(t){
  if (state.phase !== "build"){ toast("Roll for elements first.", "bad"); return; }
  if (state.restocked[t]){ toast(`Tier ${t} already restocked this turn.`, "bad"); return; }
  if (!state.decks[t].length){ toast(`Tier ${t} deck is empty.`, "bad"); return; }
  state.decks[t] = state.decks[t].concat(state.river[t]);
  state.river[t] = state.decks[t].splice(0, Math.min(RIVER_SIZE[t], state.decks[t].length));
  state.restocked[t] = true;
  log(`${me().name} restocks Tier ${t}`);
  render();
  const el = document.querySelector(`.deck[data-tier="${t}"]`);
  if (el){ el.classList.remove("restocked"); void el.offsetWidth; el.classList.add("restocked"); }
  save();
}

function endTurn(){
  if (state.phase !== "build") return;
  state.active = (state.active + 1) % state.players.length;
  // The turn counter only advances once every seat has played, so every
  // player gets the same TURN_LIMIT turns.
  if (state.active === 0) state.turn++;
  state.phase = "travel";
  state.restocked = { I:false, II:false, III:false };
  if (state.turn > TURN_LIMIT) return endGame();
  render();
  save();
}

function scoreOf(p){
  const base = p.items.reduce((n, name) => n + ITEM[name].points, 0);
  const allSeen = Object.keys(MAP_NODE_POS).every(s => p.visited[s]);
  return base + (allSeen ? STATIONS_VISITED_BONUS : 0) + p.lines.length * BINGO_LINE_BONUS;
}
function scoreBreakdown(p){
  const base = p.items.reduce((n, name) => n + ITEM[name].points, 0);
  const allSeen = Object.keys(MAP_NODE_POS).every(s => p.visited[s]);
  return [
    ["Items built (" + p.items.length + ")", base],
    ["All 8 stations", allSeen ? STATIONS_VISITED_BONUS : 0],
    ["Bingo x" + p.lines.length, p.lines.length * BINGO_LINE_BONUS],
  ];
}

function log(msg){
  state.log.push({ t: state.turn, msg });
  if (state.log.length > 200) state.log.shift();
}

function endGame(){
  state.over = true;
  render();
  save();
  showScoreboard(true);
}

