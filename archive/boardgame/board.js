function showRoll(station, dice, faces, done){
  const veil = $("rollVeil");
  $("rollStation").textContent = station;
  veil.hidden = false;
  let ticks = 0;
  const paint = final => {
    $("rollDice").innerHTML = faces.map(f => {
      const v = final ? f : rndInt(6) + 1;
      const sym = dice[v - 1];
      return `<span class="rdie" style="--el:${ELEMENT_COLOR[sym] || "#ccc"}">
        ${esc(sym)}${pipsHTML(v)}</span>`;
    }).join("");
  };
  const iv = setInterval(() => {
    paint(false);
    if (++ticks >= 6){
      clearInterval(iv);
      paint(true);
      setTimeout(() => { veil.hidden = true; done(); }, 520);
    }
  }, 70);
}

