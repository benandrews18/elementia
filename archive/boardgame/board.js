document.addEventListener("click", e => {
  const seatBtn = e.target.closest("[data-seats]");
  if (seatBtn){
    pendingSeats = +seatBtn.dataset.seats;
    document.querySelectorAll("[data-seats]").forEach(b =>
      b.classList.toggle("on", +b.dataset.seats === pendingSeats));
    return;
  }

  // Conversion target picked inside the element modal.
  const convTo = e.target.closest("[data-conv-to]");
  if (convTo){ convert(convTo.dataset.convFrom, convTo.dataset.convTo); return; }

  const act = e.target.closest("[data-act]");
  if (act){
    switch (act.dataset.act){
      case "close":   closeModal(); return;
      case "rules":   showRules(); return;
      case "scores":  showScoreboard(false); return;
      case "newgame": showNewGame(); return;
      case "start":   closeModal(); newGame(pendingSeats); render(); return;
      case "roll":    roll(); return;
      case "end":     endTurn(); return;
      case "convert": showConvert(); return;
      case "tray":    toggleTray(); return;
      case "restock-help":
        openModal("Restocking",
          `<p>Each tier deck is a real, shuffled deck — the face-up row beside it is only a window
            onto the top of it. Clicking a deck puts that whole row on the bottom and deals a fresh
            one, once per tier per turn.</p>
          <p>It is how you dig for a particular card rather than waiting on the shuffle to
            offer it.</p>`);
        return;
    }
  }

  const deck = e.target.closest(".deck");
  if (deck && !deck.disabled){ restock(deck.dataset.tier); return; }

  const go = e.target.closest("[data-travel]");
  if (go && !go.disabled){
    const name = go.dataset.travel;
    if (state.phase === "travel" && !state.over && canTravel(me(), name)) travel(name);
    else if (go.classList.contains("node") || go.classList.contains("map-note"))
      toast(state.over ? "The game is over." :
        state.phase !== "travel" ? "You have already moved this turn." :
        me().at === name ? "You are already here — you must move." :
        `${name} is not connected to ${me().at}.`, "bad");
    else showStation(name);
    return;
  }
  // The element bars are station info, not travel buttons.
  const bar = e.target.closest("[data-station]");
  if (bar){ showStation(bar.dataset.station); return; }

  const card = e.target.closest("[data-build]");
  if (card){
    const name = card.dataset.build;
    if (state.phase === "build" && !state.over && canBuild(me(), name)) build(name);
    else showItem(name);
    return;
  }

  const el = e.target.closest("[data-el]");
  if (el){ showElement(el.dataset.el); return; }

  const pin = e.target.closest("[data-pin]");
  if (pin){
    const p = me(), name = pin.dataset.pin;
    const i = p.pinned.indexOf(name);
    if (i === -1) p.pinned.push(name); else p.pinned.splice(i, 1);
    renderBingo();
    save();
    return;
  }

  if (e.target === $("veil")) closeModal();
});

document.addEventListener("keydown", e => {
  if (e.key === "Escape") closeModal();
});

