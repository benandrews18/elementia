const SAVE_KEY = "elementia_board_v2";
let state = null;

const me = () => state.players[state.active];
const owns = (p, name) => p.items.includes(name);
const count = (p, sym) => p.elements[sym] || 0;
const myTurn = () => !state.over;

function freshPlayer(i, n){
  return {
    name: n > 1 ? "Player " + (i + 1) : "You",
    color: SEAT_COLORS[i % SEAT_COLORS.length],
    at: null,                 // null = has not chosen a starting station yet
    elements: {},
    items: [],
    visited: {},
    bingo: drawBingoCard(),
    lines: [],                // indices into bingoLines(), scored once ever
    pinned: [],
  };
}

function newGame(seats){
  const seed = (Math.random() * 4294967296) >>> 0;
  rngState = seed;
  state = {
    v: 2,
    seed,
    version: DATA.version,
    seats,
    turn: 1,
    active: 0,
    phase: "travel",
    over: false,
    decks: {},
    river: {},
    restocked: { I:false, II:false, III:false },
    capstoneOwner: {},
    players: [],
    log: [],
  };
  DECK_TIERS.forEach(t => {
    const pool = [];
    TIER_POOL[t].forEach(n => {
      for (let i = 0; i < COPIES(t, seats); i++) pool.push(n);
    });
    const deck = shuffle(pool);
    state.river[t] = deck.splice(0, RIVER_SIZE[t]);
    state.decks[t] = deck;
  });
  // Bingo cards are drawn off the same seeded stream, so the whole table
  // is reproducible from state.seed alone.
  for (let i = 0; i < seats; i++) state.players.push(freshPlayer(i, seats));
  save();
}

function save(){
  try { localStorage.setItem(SAVE_KEY, JSON.stringify(Object.assign({}, state, { rng: rngState }))); }
  catch(e){}
}
function load(){
  try {
    const raw = localStorage.getItem(SAVE_KEY);
    if (!raw) return false;
    const s = JSON.parse(raw);
    if (!s || s.v !== 2 || !Array.isArray(s.players) || !s.players.length) return false;
    // A save written against different content (recipes/points/roster) can
    // reference items that no longer exist -- start fresh rather than
    // render a half-broken board.
    if (s.version !== DATA.version) return false;
    rngState = s.rng || s.seed || 1;
    delete s.rng;
    state = s;
    return true;
  } catch(e){ return false; }
}

