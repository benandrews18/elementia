const EL_RE = /^[A-Z][a-z]?$/;
const esc = s => String(s).replace(/[&<>"']/g, c =>
  ({ "&":"&amp;", "<":"&lt;", ">":"&gt;", '"':"&quot;", "'":"&#39;" }[c]));
/* Same contract as elementia.html's em(): the emoji field is a lookup
   key, never a glyph to render -- every icon resolves to bundled art. */
const em = key => ICONS[key] || esc(key);

const STATION_BY_NAME = {};
DATA.stations.forEach(s => { STATION_BY_NAME[s.name] = s; });

function parseRecipe(str){
  return str.split("+").map(t => t.trim()).filter(Boolean).map(tok => {
    const catalyst = tok.endsWith("*");
    tok = tok.replace(/\*/g, "").trim();
    if (EL_RE.test(tok)) return { name:tok, kind:"element", emoji:"", catalyst };
    const sp = tok.indexOf(" ");
    return {
      name: sp >= 0 ? tok.slice(sp + 1).trim() : tok,
      kind: "item",
      emoji: sp >= 0 ? tok.slice(0, sp) : "",
      catalyst,
    };
  });
}

/* One entry per unique CORE_SET item. A handful are multi-home (sold at
   two stations); the first listing wins, and that station gives the card
   its colour and its badge. It no longer gates anything -- any card can
   be built from anywhere -- so this is provenance only. */
const ITEM = {};

DATA.stations.forEach(s => {
  [...s.shop, s.capstone].forEach(([emoji, name, tier, recipe, points]) => {
    if (!CORE_SET.has(s.name + "|" + name) || ITEM[name]) return;
    ITEM[name] = {
      name, emoji, tier, points, recipe,
      station: s.name,
      suit: DATA.suits[s.suit].color,
      soft: DATA.suits[s.suit].soft,
      reqs: parseRecipe(recipe),
    };
  });
});

const ALL_ITEMS = Object.keys(ITEM);
const DECK_TIERS = ["I", "II", "III"];

/* Deck tier is decided by an item's POINT value, not by build_guide.py's
   MATERIAL/COMPONENT/CREATION field. The two do not agree -- the tier
   field describes what an item IS, these bands describe what it is WORTH
   -- so e.g. Tools (a CREATION worth 3) banks into Tier I. The bands
   partition the Classic catalogue exactly: 25 / 28 / 18, with no regular
   item reaching 20 and every capstone at 20 or above, so the capstone row
   needs no band of its own. */
const TIER_BANDS = [["I", 4], ["II", 10], ["III", 19]];
const tierOf = name => ITEM[name].tier === "CAPSTONE" ? "CAP"
  : (TIER_BANDS.find(b => ITEM[name].points <= b[1]) || TIER_BANDS[2])[0];

const TIER_POOL = { I:[], II:[], III:[] };
const CAPSTONES = [];
ALL_ITEMS.forEach(n => {
  const t = tierOf(n);
  if (t === "CAP") CAPSTONES.push(n); else TIER_POOL[t].push(n);
});

/* Face-up row width per tier -- the mockup's own 7 / 5 / 3 pyramid. */
const RIVER_SIZE = { I:7, II:5, III:3 };
const DECK_COLOR = { I:"#3fa9f5", II:"#f5c542", III:"#e2543b" };
const TIER_LABEL = { I:"1–4 pts", II:"5–10 pts", III:"11–19 pts" };

/* Deck copies scale with the table: Tier I holds enough for every player
   to own one, Tier II is scarcer, Tier III scarcer still. Capstones are
   unique -- exactly one of each exists, so they are genuinely contested.
   Solo collapses to one copy of everything, which is what a single player
   could ever own anyway. */
const COPIES = (tier, seats) => ({
  I:   seats,
  II:  Math.max(1, seats - 1),
  III: Math.max(1, seats - 2),
}[tier]);

// Rules constants.
const TURN_LIMIT = 20;          // every player gets this many turns
const CONVERT_COST = 3;         // 3 of one element -> 1 of any other

/* ------------------------------------------------------------------
   CRAFT_COST -- extra element tokens burned per card built, on top of
   whatever elements the recipe itself names. Paid from whatever the
   player is holding (most plentiful first).

   This is INVENTED, not one of the rules as given, and it exists because
   the recipes alone cannot make elements scarce. Measured against this
   catalogue: the whole 79-item set names only 58 element tokens, 50 of
   its items name NONE at all, and every one of the 8 capstones is a pure
   item-on-item combination. A 20-turn game deals 120 tokens. So above
   Tier I the tree costs nothing and a solo player finishes it with tokens
   to spare -- elements gate the bottom row and nothing else.

   Cutting the dice does not fix that: at 3 dice a turn a player still
   ends holding ~27 unspent tokens while the game starves, because the
   leftovers are the WRONG elements. It is a matching problem, not a
   quantity one. A flat per-craft cost is what actually drains the pool.

   Tuned by simulation (10-run batches, a bot that converts toward what it
   needs): at 1/2/3/0 a solo game ends holding 2.7 tokens, having built
   ~40 of 79 items, scoring 188-311. Capstones are exempt -- they are
   already gated behind owning four to six finished ingredients, and they
   are the prize.

   Set every value to 0 to remove the rule entirely; nothing else depends
   on it. ------------------------------------------------------------ */
const CRAFT_COST = { I:1, II:2, III:3, CAP:0 };

