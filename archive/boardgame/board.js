const bingoEligible = () => ALL_ITEMS.filter(n => ITEM[n].points >= BINGO_MIN_POINTS);

/* Same shape as the digital game's drawBingoCard(): one guaranteed
   capstone dead centre, a second common, a third rare. */
function drawBingoCard(){
  const eligible = bingoEligible();
  const caps = shuffle(eligible.filter(n => ITEM[n].tier === "CAPSTONE"));
  const rest = eligible.filter(n => ITEM[n].tier !== "CAPSTONE");
  const picked = [caps[0]];
  if (rnd() < BINGO_SECOND_CAPSTONE_CHANCE){
    picked.push(caps[1]);
    if (rnd() < BINGO_THIRD_CAPSTONE_CHANCE) picked.push(caps[2]);
  }
  const centre = picked[0], extras = picked.slice(1);
  const need = BINGO_SIZE * BINGO_SIZE;
  const others = shuffle([...extras, ...shuffle(rest).slice(0, need - 1 - extras.length)]);
  const at = Math.floor(BINGO_SIZE / 2) * BINGO_SIZE + Math.floor(BINGO_SIZE / 2);
  return [...others.slice(0, at), centre, ...others.slice(at)];
}
function bingoLines(){
  const n = BINGO_SIZE, lines = [], at = (r,c) => r * n + c;
  for (let r = 0; r < n; r++) lines.push(Array.from({length:n}, (_,c) => at(r,c)));
  for (let c = 0; c < n; c++) lines.push(Array.from({length:n}, (_,r) => at(r,c)));
  lines.push(Array.from({length:n}, (_,i) => at(i,i)));
  lines.push(Array.from({length:n}, (_,i) => at(i, n - 1 - i)));
  return lines;
}
/* Awarded once per line, ever -- same "lifetime, never un-earned" shape
   as the stations-visited bonus. */
function checkBingo(p){
  const won = [];
  bingoLines().forEach((line, i) => {
    if (p.lines.includes(i)) return;
    if (line.every(idx => owns(p, p.bingo[idx]))){ p.lines.push(i); won.push(i); }
  });
  return won;
}

