/* The station panel from images/Board Game View 2: a dark plate carrying
   the station's icon and name, the words "elements found here", and six
   white tiles bordered in each element's own suit colour with that
   element's die face alongside.

   The two side panels are this same plate turned a quarter-turn, and they
   turn OPPOSITE ways so each one's label lands on the outer edge: the
   Ocean's anticlockwise (faces reading 6 at the top down to 1), the
   Observatory's clockwise (1 at the top down to 6). Pips sit inboard on
   both. Only the name label rotates with the plate -- the element letters
   stay upright. */
function stationPanelHTML(name, orient, side){
  const s = STATION_BY_NAME[name];
  const dice = sortedDice(s).map((sym, i) => ({ sym, face: i + 1 }));
  const order = (orient === "v" && side === "left") ? dice.slice().reverse() : dice;
  const cls = orient === "v" ? `v ${side}` : "h";
  return `<div class="stpanel ${cls}" style="--suit:${DATA.suits[s.suit].color}"
      data-station="${esc(name)}" title="${esc(name)}">
    <div class="stpanel-label">
      <span class="stpanel-name">${em(s.emoji)}<b>${esc(name)}</b></span>
      <span class="stpanel-sub">Elements found here</span>
    </div>
    <div class="stpanel-tiles">
      ${order.map(d => `<span class="eltile-wrap">
        <span class="eltile" style="--el:${ELEMENT_COLOR[d.sym] || "#8a94a6"}">${esc(d.sym)}</span>
        <span class="elface">${pipsHTML(d.face)}</span>
      </span>`).join("")}
    </div>
  </div>`;
}

/* Split the 8 stations into top / bottom / side purely from their own
   board positions, so re-tuning MAP_NODE_POS upstream re-sorts them
   automatically instead of needing a matching edit here. */
function stationGroups(){
  const rows = Object.keys(MAP_NODE_POS).map(n => ({ n, p: boardPos(n) }));
  const pick = f => rows.filter(f).sort((a,b) => a.p[0] - b.p[0]).map(r => r.n);
  return {
    top:    pick(r => r.p[1] < 35),
    bottom: pick(r => r.p[1] > 65),
    sides:  pick(r => r.p[1] >= 35 && r.p[1] <= 65),
  };
}

function renderBoard(){
  const p = me();
  const g = stationGroups();

  // preserveAspectRatio="none" makes the two axes scale by wildly different
  // factors, so a plain stroke-width would render as a thin, direction-
  // dependent smear; vector-effect keeps every dash the same real width.
  const isShortcut = (a,b) => (a === SHORTCUT[0] && b === SHORTCUT[1]) || (a === SHORTCUT[1] && b === SHORTCUT[0]);
  $("mapLines").innerHTML = MAP_EDGES.filter(([a,b]) => !isShortcut(a,b)).map(([a,b]) => {
    const [x1,y1] = boardPos(a), [x2,y2] = boardPos(b);
    const live = p.at === a || p.at === b;
    return `<path d="M${x1} ${y1} L${x2} ${y2}" vector-effect="non-scaling-stroke"
      stroke="${live ? "#ffe680" : "#f2c94c"}" stroke-opacity="${live ? 1 : .78}"
      stroke-width="${live ? 9 : 7}" stroke-dasharray="10 11" />`;
  }).join("");

  // Element bars ride the map itself now (Style 1/2), anchored to their
  // own node's axis rather than sitting in a separate rail.
  const bars =
    g.top.map(n => {
      const [x] = boardPos(n);
      return `<div class="bar-slot top" style="left:${x}%">${stationPanelHTML(n, "h")}</div>`;
    }).join("") +
    g.bottom.map(n => {
      const [x] = boardPos(n);
      return `<div class="bar-slot bottom" style="left:${x}%">${stationPanelHTML(n, "h")}</div>`;
    }).join("") +
    g.sides.map(n => {
      const [x,y] = boardPos(n);
      const side = x < 50 ? "left" : "right";
      return `<div class="bar-slot ${side}" style="top:${y}%">${stationPanelHTML(n, "v", side)}</div>`;
    }).join("");

  // The node itself is icon-only now -- the name lives on its panel.
  $("mapNodes").innerHTML = Object.keys(MAP_NODE_POS).map(name => {
    const s = STATION_BY_NAME[name];
    const [x,y] = boardPos(name);
    const can = state.phase === "travel" && !state.over && canTravel(p, name);
    const cls = ["node", can ? "reachable" : "", p.at === name ? "here" : "",
                 p.visited[name] ? "visited" : ""].join(" ");
    return `<button type="button" class="${cls}" style="--suit:${DATA.suits[s.suit].color};left:${x}%;top:${y}%"
      data-travel="${esc(name)}" title="${esc(name)}${can ? " — click to travel" : ""}">
      <span class="node-icon">${em(s.emoji)}</span>
    </button>`;
  }).join("") + pawnsHTML();

  $("mapFloat").innerHTML = bars + shortcutHTML(p);
}

function pawnsHTML(){
  // Fanned around the node so 2-4 seats standing together stay countable.
  const byStation = {};
  state.players.forEach((p, i) => {
    if (!p.at) return;
    (byStation[p.at] = byStation[p.at] || []).push({ p, i });
  });
  return Object.keys(byStation).map(st => {
    const [x,y] = boardPos(st);
    const here = byStation[st];
    return here.map(({p,i}, k) => {
      const spread = (k - (here.length - 1) / 2) * 3.4;
      return `<span class="pawn" style="--pawn:${p.color};left:${x + spread}%;top:${y + 7}%"
        title="${esc(p.name)}">${state.players.length > 1 ? i + 1 : ""}</span>`;
    }).join("");
  }).join("");
}

function shortcutHTML(p){
  if (!p.visited[SHORTCUT[1]]) return "";
  const label = (from, to, dx) => {
    const [x,y] = boardPos(from);
    const can = state.phase === "travel" && !state.over && canTravel(p, to);
    return `<button type="button" class="map-note" style="left:${x + dx}%;top:${y - 12}%"
      data-travel="${esc(to)}" ${can ? "" : "disabled"}>To ${esc(to)}</button>`;
  };
  return label(SHORTCUT[0], SHORTCUT[1], 13) + label(SHORTCUT[1], SHORTCUT[0], -13);
}

